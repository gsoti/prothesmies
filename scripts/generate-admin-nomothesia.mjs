import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const EXPECTED_CODE_ID = 'kdiokd';
const ARTICLE_KEY = '114';
const EXPECTED_PARAGRAPHS = [1, 2, 3, 4];
const CITATION = '114 παρ. 2 ΚΔΔ';
export const PAREMVASI_HIGHLIGHT = 'Η παρέμβαση ασκείται με ιδιαίτερο έγγραφο, το οποίο κατατίθεται στη γραμματεία του δικαστηρίου στο οποίο εκκρεμεί το σχετικό ένδικο βοήθημα ή μέσο και, με τη φροντίδα του παρεμβαίνοντος, επιδίδεται, με την ποινή του απαραδέκτου, σε κυρωμένο αντίγραφο στους διαδίκους τουλάχιστον έξι (6) πλήρεις ημέρες πριν από τη συζήτηση.';

const defaultOutput = fileURLToPath(
    new URL('../src/generated/admin-nomothesia.generated.ts', import.meta.url)
);

function requireRecord(value, label) {
    if (!value || typeof value !== 'object' || Array.isArray(value)) {
        throw new Error(`${label} must be an object`);
    }
    return value;
}

export function normalizeArticle114(bodyText) {
    if (typeof bodyText !== 'string' || !bodyText.trim()) {
        throw new Error('Article 114 bodyText must be a non-empty string');
    }

    const text = bodyText.replace(/\s+/gu, ' ').trim();
    const candidates = [];
    const marker = /(?:^|\s)[«"“]?(\d+)\.\s/gu;
    let match;

    while ((match = marker.exec(text)) !== null) {
        const leadingWhitespace = /^\s/u.test(match[0]) ? 1 : 0;
        candidates.push({
            number: Number(match[1]),
            start: match.index + leadingWhitespace,
        });
    }

    const paragraphStarts = [];
    let candidateIndex = 0;
    for (const expected of EXPECTED_PARAGRAPHS) {
        while (
            candidateIndex < candidates.length &&
            candidates[candidateIndex].number !== expected
        ) {
            candidateIndex += 1;
        }
        if (candidateIndex >= candidates.length) {
            throw new Error(`Article 114 is missing sequential paragraph ${expected}`);
        }
        paragraphStarts.push(candidates[candidateIndex]);
        candidateIndex += 1;
    }

    const paragraphs = paragraphStarts.map((paragraph, index) => {
        const end = paragraphStarts[index + 1]?.start ?? text.length;
        return text.slice(paragraph.start, end).replace(/\s+/gu, ' ').trim();
    });
    const normalized = paragraphs.join('\n\n');

    if (!normalized.includes('άρθρου 126.')) {
        throw new Error('Article 114 does not contain the expected contiguous Article 126 reference');
    }
    if (!normalized.includes(PAREMVASI_HIGHLIGHT)) {
        throw new Error('The Παρέμβαση highlight was not found verbatim in Article 114');
    }

    return normalized;
}

export function buildGeneratedAdminNomothesia(sourceJson, sourceSha256) {
    const root = requireRecord(sourceJson, 'Source JSON');
    const source = requireRecord(root.source, 'source');
    if (source.codeId !== EXPECTED_CODE_ID) {
        throw new Error(`Expected source.codeId to be '${EXPECTED_CODE_ID}'`);
    }
    if (!Array.isArray(root.articles)) {
        throw new Error('articles must be an array');
    }

    const matches = root.articles.filter(article =>
        article?.articleKey === ARTICLE_KEY && article?.articleNumber === 114
    );
    if (matches.length !== 1) {
        throw new Error(`Expected exactly one Article 114 entry; found ${matches.length}`);
    }

    const text = normalizeArticle114(matches[0].bodyText);
    const provenance = {
        codeId: source.codeId,
        sourceUrl: source.sourceUrl,
        scrapedAt: source.scrapedAt,
        latestModification: source.latestModification,
        sha256: sourceSha256,
    };
    for (const [key, value] of Object.entries(provenance)) {
        if (typeof value !== 'string' || !value) {
            throw new Error(`source.${key} must be a non-empty string`);
        }
    }

    return { provenance, text };
}

function escapeTemplateLiteral(value) {
    return value
        .replace(/\\/gu, '\\\\')
        .replace(/`/gu, '\\`')
        .replace(/\$\{/gu, '\\${');
}

export function renderGeneratedModule(data) {
    const { provenance, text } = data;
    return `/* This file is generated by scripts/generate-admin-nomothesia.mjs. Do not edit manually. */

export const ADMIN_NOMOTHESIA_SOURCE = ${JSON.stringify(provenance, null, 4)} as const;

export const GENERATED_ADMIN_NOMOTHESIA = {
    paremvasi: {
        article: ${JSON.stringify(CITATION)},
        text: \`${escapeTemplateLiteral(text)}\`,
        highlighted: [
            ${JSON.stringify(PAREMVASI_HIGHLIGHT)},
        ],
    },
} as const;
`;
}

function parseArgs(args) {
    let source;
    let output = defaultOutput;
    let check = false;

    for (let index = 0; index < args.length; index += 1) {
        const arg = args[index];
        if (arg === '--source') source = args[++index];
        else if (arg === '--output') output = args[++index];
        else if (arg === '--check') check = true;
        else if (arg === '--help') {
            return { help: true };
        } else {
            throw new Error(`Unknown argument: ${arg}`);
        }
    }

    if (!source) throw new Error('--source <kdioikd-pilot.json> is required');
    return { source: resolve(source), output: resolve(output), check, help: false };
}

async function main() {
    const options = parseArgs(process.argv.slice(2));
    if (options.help) {
        console.log('Usage: node scripts/generate-admin-nomothesia.mjs --source <kdioikd-pilot.json> [--output <file>] [--check]');
        return;
    }

    const sourceBuffer = await readFile(options.source);
    const sourceJson = JSON.parse(sourceBuffer.toString('utf8'));
    const sourceSha256 = createHash('sha256').update(sourceBuffer).digest('hex');
    const generated = renderGeneratedModule(
        buildGeneratedAdminNomothesia(sourceJson, sourceSha256)
    );

    if (options.check) {
        const current = await readFile(options.output, 'utf8');
        if (current !== generated) {
            throw new Error(`Generated nomothesia is stale: ${options.output}`);
        }
        console.log(`Generated nomothesia is current: ${options.output}`);
        return;
    }

    await writeFile(options.output, generated, 'utf8');
    console.log(`Generated ${options.output} from ${options.source}`);
}

const invokedPath = process.argv[1] ? resolve(process.argv[1]) : null;
if (invokedPath === fileURLToPath(import.meta.url)) {
    main().catch(error => {
        console.error(error instanceof Error ? error.message : error);
        process.exitCode = 1;
    });
}
